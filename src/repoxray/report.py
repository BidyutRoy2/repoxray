"""Reporters: ARCHITECTURE.md, machine-readable JSON, and an HTML map."""

from __future__ import annotations

import html
import json
from collections import defaultdict

from .analysis import DeadFunction, Hotspot, Summary
from .graph import build_edges
from .scanner import ModuleInfo


def to_dict(root: str, modules: dict[str, ModuleInfo], counts: dict,
            edges: dict[str, set[str]], cycles: list[list[str]],
            entries: list[str], orphans_list: list[str],
            dead: list[DeadFunction], spots: list[Hotspot],
            summary: Summary) -> dict:
    return {
        "root": root,
        "summary": {
            "modules": summary.modules,
            "total_lines": summary.total_lines,
            "total_functions": summary.total_functions,
            "total_classes": summary.total_classes,
            "internal_edges": summary.total_edges,
            "external_packages": summary.external_packages,
            "python_files": counts["python_files"],
            "other_files": counts["other_files"],
            "parse_errors": counts["parse_errors"],
        },
        "entry_points": entries,
        "orphans": orphans_list,
        "cycles": cycles,
        "dead_code": [{"module": d.module, "name": d.name, "line": d.lineno}
                      for d in dead],
        "hotspots": [{"module": h.module, "name": h.name,
                      "complexity": h.complexity} for h in spots],
        "modules": {
            name: {
                "path": info.path,
                "lines": info.lines,
                "functions": sorted(info.defines),
                "classes": info.classes,
                "imports": sorted(info.imports),
                "external_imports": sorted(info.external_imports),
                "parse_error": info.parse_error,
            }
            for name, info in sorted(modules.items())
        },
        "edges": {src: sorted(t) for src, t in sorted(edges.items()) if t},
    }


def to_markdown(root: str, modules: dict[str, ModuleInfo], counts: dict,
                edges: dict[str, set[str]], cycles: list[list[str]],
                entries: list[str], orphans_list: list[str],
                dead: list[DeadFunction], spots: list[Hotspot],
                summary: Summary) -> str:
    """The ARCHITECTURE.md a new contributor (or agent) reads first."""
    lines: list[str] = []
    lines.append(f"# Architecture map — `{root}`")
    lines.append("")
    lines.append("> Generated by [repoxray](https://github.com/BidyutRoy2/repoxray). "
                 "Read this before you change anything: it is the map, not the territory.")
    lines.append("")
    lines.append("## At a glance")
    lines.append("")
    lines.append("| Metric | Value |")
    lines.append("|---|---|")
    lines.append(f"| Python modules | {summary.modules} |")
    lines.append(f"| Lines of Python | {summary.total_lines} |")
    lines.append(f"| Functions / classes | {summary.total_functions} / {summary.total_classes} |")
    lines.append(f"| Internal import edges | {summary.total_edges} |")
    lines.append(f"| External packages used | {summary.external_packages} |")
    lines.append(f"| Files that failed to parse | {counts['parse_errors']} |")
    lines.append("")
    lines.append("## Start here (entry points)")
    lines.append("")
    if entries:
        for entry in entries:
            info = modules[entry]
            lines.append(f"- `{entry}` — `{info.path}` ({info.lines} lines)")
    else:
        lines.append("_No entry points found — every module is imported by another._")
    lines.append("")
    lines.append("## Module map")
    lines.append("")
    lines.append("| Module | Lines | Imports | Imported by |")
    lines.append("|---|---|---|---|")
    imported_by: dict[str, list[str]] = defaultdict(list)
    for src, targets in edges.items():
        for target in targets:
            imported_by[target].append(src)
    for name in sorted(modules):
        info = modules[name]
        imports = ", ".join(f"`{i}`" for i in sorted(info.imports)) or "—"
        by = ", ".join(f"`{i}`" for i in sorted(imported_by.get(name, []))) or "—"
        lines.append(f"| `{name}` | {info.lines} | {imports} | {by} |")
    lines.append("")
    if cycles:
        lines.append("## ⚠️ Import cycles")
        lines.append("")
        lines.append("Cycles make modules untestable in isolation. Break them by "
                     "extracting the shared piece into a lower-level module.")
        lines.append("")
        for cycle in cycles:
            lines.append(f"- {' → '.join(f'`{c}`' for c in cycle)} → `{cycle[0]}`")
        lines.append("")
    if orphans_list:
        lines.append("## Orphan modules")
        lines.append("")
        lines.append("Nothing imports these and they import nothing internal. "
                     "Candidates for deletion or for wiring in:")
        lines.append("")
        for name in orphans_list:
            lines.append(f"- `{name}` (`{modules[name].path}`)")
        lines.append("")
    if dead:
        lines.append("## Possibly dead code")
        lines.append("")
        lines.append("Functions never called anywhere in the project. "
                     "Dynamically-dispatched calls (`getattr`, plugins) can cause "
                     "false positives — verify before deleting.")
        lines.append("")
        for item in dead:
            lines.append(f"- `{item.module}.{item.name}` (line {item.lineno})")
        lines.append("")
    if spots:
        lines.append("## Complexity hotspots (complexity ≥ 5)")
        lines.append("")
        for item in spots:
            lines.append(f"- `{item.module}.{item.name}` — complexity {item.complexity}")
        lines.append("")
    errors = [m for m in modules.values() if m.parse_error]
    if errors:
        lines.append("## Files that failed to parse")
        lines.append("")
        for info in errors:
            lines.append(f"- `{info.path}`: {info.parse_error}")
        lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("_Regenerate with `repoxray scan <path> --format md`._")
    return "\n".join(lines) + "\n"


def to_html(root: str, modules: dict[str, ModuleInfo],
            edges: dict[str, set[str]], depth: dict[str, int],
            cycles: list[list[str]], entries: list[str],
            orphans_list: list[str], dead: list[DeadFunction]) -> str:
    """A single self-contained, dark-mode-aware map page.

    Layout is deliberately simple and honest: modules are grouped into
    columns by import depth, so entry points sit on the left and shared
    low-level modules on the right. Edges are drawn as SVG lines between
    column positions — no JavaScript framework, no external assets.
    """
    by_depth: dict[int, list[str]] = defaultdict(list)
    for name, level in depth.items():
        by_depth[level].append(name)
    max_depth = max(by_depth) if by_depth else 0
    col_w, row_h = 260, 54
    width = (max_depth + 1) * col_w + 40
    positions: dict[str, tuple[int, int]] = {}
    for level in sorted(by_depth):
        for i, name in enumerate(sorted(by_depth[level])):
            positions[name] = (20 + level * col_w, 20 + i * row_h)
    height = max((len(v) for v in by_depth.values()), default=1) * row_h + 40

    esc = html.escape
    parts: list[str] = []
    parts.append("<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n")
    parts.append(f"<title>repoxray map — {esc(root)}</title>\n")
    parts.append("""<style>
:root{color-scheme:light dark}
body{font-family:system-ui,-apple-system,Segoe UI,Roboto,sans-serif;margin:0;
  background:#f6f7f9;color:#16181d}
@media(prefers-color-scheme:dark){body{background:#0e1116;color:#e6e8eb}}
header{padding:24px 32px;border-bottom:1px solid #d0d5dd}
@media(prefers-color-scheme:dark){header{border-color:#262b33}}
h1{margin:0 0 6px;font-size:22px} p{margin:4px 0;color:#5b6470}
@media(prefers-color-scheme:dark){p{color:#9aa3af}}
.badge{display:inline-block;padding:2px 10px;border-radius:999px;font-size:12px;
  background:#e8f0fe;color:#1a56db;margin-right:6px}
@media(prefers-color-scheme:dark){.badge{background:#1c2b4a;color:#8fb4ff}}
.warn{background:#fef3c7;color:#92400e}
@media(prefers-color-scheme:dark){.warn{background:#3a2a0a;color:#fbbf24}}
main{padding:24px 32px;overflow:auto}
.node{fill:#ffffff;stroke:#c9ced6;stroke-width:1.2}
@media(prefers-color-scheme:dark){.node{fill:#171c24;stroke:#2e3542}}
.edge{stroke:#9aa3af;stroke-width:1.2}
.label{font:12px system-ui,sans-serif;fill:#16181d}
@media(prefers-color-scheme:dark){.label{fill:#e6e8eb}}
.sub{font:10px system-ui,sans-serif;fill:#5b6470}
@media(prefers-color-scheme:dark){.sub{fill:#9aa3af}}
.entry{stroke:#1a56db;stroke-width:2}
.cycle{stroke:#dc2626}
section{max-width:900px}
li{margin:4px 0}
</style></head><body>\n""")
    parts.append(f"<header><h1>🗺️ Architecture map — {esc(root)}</h1>\n")
    parts.append(f"<p>{len(modules)} modules · {sum(len(t) for t in edges.values())} "
                 "internal edges · left = entry points, right = shared foundations</p>\n")
    if entries:
        parts.append("<p>" + "".join(
            f"<span class=\"badge\">▶ {esc(e)}</span>" for e in entries) + "</p>\n")
    if cycles:
        parts.append("<p><span class=\"badge warn\">⚠️ "
                     f"{len(cycles)} import cycle(s)</span></p>\n")
    parts.append("</header>\n<main>\n")
    parts.append(f"<svg width=\"{width}\" height=\"{height}\" "
                 "xmlns=\"http://www.w3.org/2000/svg\">\n")
    for src, targets in edges.items():
        if src not in positions:
            continue
        x1, y1 = positions[src]
        for target in targets:
            if target not in positions:
                continue
            x2, y2 = positions[target]
            in_cycle = any(src in c and target in c for c in cycles)
            cls = "edge cycle" if in_cycle else "edge"
            parts.append(
                f"<line class=\"{cls}\" x1=\"{x1 + 220}\" y1=\"{y1 + 20}\" "
                f"x2=\"{x2}\" y2=\"{y2 + 20}\" />\n")
    for name, (x, y) in positions.items():
        info = modules[name]
        cls = "node entry" if name in entries else "node"
        parts.append(f"<g><rect class=\"{cls}\" x=\"{x}\" y=\"{y}\" width=\"220\" "
                     f"height=\"40\" rx=\"9\" />")
        parts.append(f"<text class=\"label\" x=\"{x + 12}\" y=\"{y + 17}\">{esc(name)}</text>")
        parts.append(f"<text class=\"sub\" x=\"{x + 12}\" y=\"{y + 32}\">"
                     f"{info.lines} lines · {len(info.defines)} fns</text></g>\n")
    parts.append("</svg>\n")
    if orphans_list:
        parts.append("<section><h2>Orphan modules</h2><ul>")
        parts.append("".join(f"<li><code>{esc(o)}</code></li>" for o in orphans_list))
        parts.append("</ul></section>\n")
    if dead:
        parts.append("<section><h2>Possibly dead code</h2><ul>")
        parts.append("".join(
            f"<li><code>{esc(d.module)}.{esc(d.name)}</code> (line {d.lineno})</li>"
            for d in dead))
        parts.append("</ul></section>\n")
    parts.append("<p>Generated by repoxray — regenerate with "
                 "<code>repoxray scan &lt;path&gt; --format html</code>.</p>\n")
    parts.append("</main></body></html>\n")
    return "".join(parts)


def build_all(root: str, modules: dict[str, ModuleInfo], counts: dict,
              edges: dict[str, set[str]], cycles: list[list[str]],
              entries: list[str], orphans_list: list[str],
              dead: list[DeadFunction], spots: list[Hotspot],
              summary: Summary, depth: dict[str, int]) -> dict[str, str]:
    """All three report formats, keyed by file extension."""
    data = to_dict(root, modules, counts, edges, cycles, entries,
                   orphans_list, dead, spots, summary)
    return {
        "md": to_markdown(root, modules, counts, edges, cycles, entries,
                          orphans_list, dead, spots, summary),
        "json": json.dumps(data, indent=2, sort_keys=True) + "\n",
        "html": to_html(root, modules, edges, depth, cycles, entries,
                        orphans_list, dead),
    }
